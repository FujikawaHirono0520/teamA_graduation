package com.example.teama_management.form;

public class RegisterForm {
    private String _usernameController;
    private String _emailController;
    private String _passwordController;
    private String _passwordConfirmController;

    public String get_usernameController() { return _usernameController; }
    public void set_usernameController(String _usernameController) { this._usernameController = _usernameController; }
    public String get_emailController() { return _emailController; }
    public void set_emailController(String _emailController) { this._emailController = _emailController; }
    public String get_passwordController() { return _passwordController; }
    public void set_passwordController(String _passwordController) { this._passwordController = _passwordController; }
    public String get_passwordConfirmController() { return _passwordConfirmController; }
    public void set_passwordConfirmController(String _passwordConfirmController) { this._passwordConfirmController = _passwordConfirmController; }
}